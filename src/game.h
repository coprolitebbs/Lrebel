/*
 * game.h — игровой режим: пошаговая партия на карте.
 *
 * Запускается параметром "-map имя_карты.map" (например,
 * "lrebel -map map1.map"): карта загружается минуя главное меню.
 *
 * Что реализовано на этом этапе:
 *   - подсчет юнитов сторон при старте карты: юниты игрока (типы
 *     персонажей с player=true в config/editor.cfg) и юниты компьютера.
 *     Победа в дальнейшем будет присваиваться стороне, которая обнулит
 *     количество юнитов оппонента;
 *   - "туман войны" — у каждой стороны свой массив раскрытых ячеек.
 *     Юниты игрока раскрывают туман игрока (его видит игрок на карте),
 *     юниты компьютера — свой отдельный туман (он нужен компьютеру,
 *     чтобы впоследствии видеть, с чем взаимодействует);
 *   - раскрытие тумана — рейтрейсингом: из центра ячейки юнита во все
 *     стороны выходят лучи; радиус = "дальность видимости" (по умолчанию
 *     12, CHAR_DEFAULT_VIS_RANGE; в будущем будет браться из описания
 *     конкретного персонажа). Если по трассировке луч встречает ячейку,
 *     помеченную в редакторе как блок запрета передвижения, то сама эта
 *     ячейка раскрывается (ее видно), но луч дальше не идет — туман за
 *     блоком не раскрывается. Раскрытое остается раскрытым постоянно.
 *     Функция раскрытия вызывается для юнитов стороны при старте каждого
 *     нового хода; сейчас, пока ходы не переключаются, — один раз при
 *     старте карты для обеих сторон;
 *   - камера: WASD; первое позиционирование — на первом юните игрока;
 *     первый ход — за игроком (индикация в верхней строке);
 *   - выбор объекта мышью (ЛКМ): юнит игрока подсвечивается мигающим
 *     светло-синим квадратиком (платформенная функция
 *     plat_draw_blink_frame), юнит противника или подбираемый предмет —
 *     мигающим зеленым квадратиком. Клик по пустой или не раскрытой
 *     ячейке снимает выбор;
 *   - окно описания выбранного объекта: по клавише "I" открывается в
 *     правой половине окна игры; закрывается крестиком-кнопкой в правом
 *     верхнем углу окна или повторным нажатием "I".
 */
#ifndef GAME_H
#define GAME_H

/* Загружает ресурсы игрового режима: config/editor.cfg (через
 * map_registry_init), img/gtiles.png и карту map_filename (см. выше).
 * Раскрывает туман войны вокруг юнитов обеих сторон и подсчитывает юниты.
 * 0 при успехе; -1, если карта не указана или не загружается. */
int  game_init(const char *map_filename);

/* Один кадр игры: ввод, логика, отрисовка и вывод кадра на экран.
 * Выделен отдельно для тестов; обычный цикл — game_run(). */
void game_frame(float dt);

/* Главный цикл игрового режима; возвращается по выходу (ESC, закрытие
 * окна) — после этого управление переходит главному меню. */
void game_run(void);

/* Освобождает ресурсы игрового режима (тайлы, карту, туман войны). */
void game_shutdown(void);

#endif /* GAME_H */
