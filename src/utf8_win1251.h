/*
 * utf8_win1251.h — перекодировка UTF-8 -> Windows-1251 (1 байт на символ).
 *
 * Используется для строк из конфигурационных файлов (chartable, title и т.п.):
 * после перекодировки каждой букве соответствует ровно один байт, что
 * упрощает поиск номера символа в таблице шрифта.
 */
#ifndef UTF8_WIN1251_H
#define UTF8_WIN1251_H

#include <stddef.h>

/*
 * Таблица перекодировки WIN1251_TABLE[256] (заполняется win1251_init_table):
 *   0x00..0x7F — ASCII, совпадает с Unicode;
 *   0xC0..0xDF — русские заглавные А..Я (порядок Windows-1251);
 *   0xE0..0xFF — русские строчные а..я;
 *   0xA8 — 'Ё', 0xB8 — 'ё';
 *   прочие позиции заполнены '?'.
 */
extern char WIN1251_TABLE[256];

/* Заполняет WIN1251_TABLE. Вызывается автоматически из utf8_to_win1251. */
void win1251_init_table(void);

/*
 * Конвертирует строку utf8_string в Windows-1251.
 * out      — буфер результата (строка завершается '\0');
 * out_size — размер буфера с учётом завершающего '\0'.
 * Возвращает число записанных байтов без '\0' или -1, если буфер мал.
 * Символы вне ASCII и русского алфавита заменяются на '?'.
 * Обрабатываются 2- и 3-байтовые последовательности UTF-8; русский алфавит
 * (U+0410..U+044F -> 0xC0..0xFF) и буквы Ё/ё (U+0401 -> 0xA8, U+0451 -> 0xB8).
 */
int utf8_to_win1251(const char *utf8_string, char *out, size_t out_size);

#endif /* UTF8_WIN1251_H */
