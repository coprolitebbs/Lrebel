/*
 * inventory_ui.h — окно инвентаря: сетка с предметами, слот основного
 * оружия, перетаскивание предметов мышью.
 *
 * Функция отображения инвентаря выделена в отдельный модуль и пригодится
 * в основной игре: окно рисуется в заданном прямоугольнике (в редакторе
 * карт — левая половина окна игры), внутри него — сетка 15x15 с
 * предметами и ниже предмет, выбранный в качестве основного оружия
 * (см. inventory.h).
 *
 * Перетаскивание — классическое: предмет выбирается левой кнопкой мыши,
 * пока кнопка удерживается — переносится, на отпускании определяется
 * ячейка под курсором: если габариты предмета помещаются в нее и
 * соседние ячейки — предмет кладется туда (со старого места снимается);
 * если не помещаются — возвращается в старую ячейку. Если предмет
 * перетащен в область отображения основного оружия и он — оружие,
 * ссылка основного оружия переключается на него. Предмет, вытащенный
 * за пределы сетки инвентаря и не в поле основного оружия, удаляется
 * из инвентаря (в основной игре будет выбрасываться на карту).
 *
 * Модуль работает только через inventory.h (логика), portable_posix.h
 * (графика, мышь), font.h (надписи) и ui.h (типовое окно).
 */
#ifndef INVENTORY_UI_H
#define INVENTORY_UI_H

#include "portable_posix.h"
#include "inventory.h"

/* Геометрия окна инвентаря (пересчитывается от прямоугольника окна). */
typedef struct inventory_ui_layout {
    int win_x, win_y, win_w, win_h; /* прямоугольник окна инвентаря      */
    int grid_x, grid_y;             /* левый верхний угол сетки, пиксели */
    int cell;                       /* размер ячейки сетки, пикселей     */
    int grid_px;                    /* сторона сетки в пикселях          */
    int wp_x, wp_y, wp_w, wp_h;     /* область основного оружия          */
} inventory_ui_layout;

/* Раскладка окна внутри прямоугольника (x,y,w,h); зависит только от
 * размеров, вызывается и отрисовкой, и обработкой мыши. */
void inventory_ui_get_layout(inventory_ui_layout *out,
                         int x, int y, int w, int h);

/* Открыто ли окно инвентаря. */
int  inventory_ui_is_open(void);

/* Открывает окно инвентаря inv в прямоугольнике (x,y,w,h); картинки
 * предметов берутся из атласа тайлов atlas. */
void inventory_ui_open(inventory *inv, const plat_image *atlas,
                       int x, int y, int w, int h);

/* Закрывает окно; перетаскиваемый предмет, если был, возвращается на
 * прежнее место. */
void inventory_ui_close(void);

/* Обработка мыши за кадр: фронты левой кнопки передаются вызывающим
 * кодом (как в ui_buttons_process_ext) — чтобы кнопки остальных окон
 * успели обработать их раньше. */
void inventory_ui_process_mouse(int left_pressed, int left_released,
                                int left_down);

/* Отрисовка окна инвентаря (сетка, предметы, слот основного оружия и
 * перетаскиваемый предмет под курсором). */
void inventory_ui_draw(void);

#endif /* INVENTORY_UI_H */
