/*
 * editor.h — редактор карт игры.
 *
 * Запускается вместо главного меню, если игра стартовала с параметром
 * командной строки "-ed":   lrebel -ed -filename map1.map
 * Карта подгружается из папки maps/; если файла нет — редактор открывается
 * с пустой картой, а файл создаётся при первом сохранении (Ctrl+S).
 * Без "-filename" используется имя unnamed.map.
 *
 * Режимы редактора (клавиши 1-4):
 *   1 — поверхности и стены (слои 1-3 карты, переключение клавишами +/-);
 *        ЛКМ — рисование: пока кнопка удерживается, тайл ставится в ячейку
 *        под курсором при её перемещении; ПКМ — взять (пипетка) тайл,
 *        лежащий в текущем слое в ячейке под курсором;
 *   2 — объекты (персонажи и оружие; свой тип выбирается клавишами +/-
 *        или в окне выбора по SPACE; ЛКМ — поставить, ПКМ — выбрать
 *        "текущий выбранный объект" в ячейке под курсором; DEL — удалить
 *        текущий выбранный объект; P — окно инвентаря выбранного объекта,
 *        O — окно добавления предмета в его инвентарь);
 *   3 — ассеты (верхний слой 4 карты; выбор — клавиши +/- или SPACE);
 *   4 — невидимые блоки запрета перемещения (ЛКМ — поставить,
 *        ПКМ — удалить, рисуются красными рамками только в редакторе).
 *
 * "Текущий выбранный объект" подсвечивается мигающей рамкой; при
 * добавлении объекта на карту он сразу становится текущим выбранным.
 * У каждого объекта карты свой инвентарь (inventory.h), он открывается
 * по клавише P в левой половине окна (inventory_ui.h) и редактируется
 * перетаскиванием предметов мышью; инвентари живут только в редакторе
 * (в файл карты не сохраняются).
 */
#ifndef EDITOR_H
#define EDITOR_H

/* Загружает ресурсы редактора: config/editor.cfg (через map_registry_init),
 * img/gtiles.png и карту map_filename (см. выше). 0 при успехе. */
int  editor_init(const char *map_filename);

/* Один кадр редактора: ввод, логика, отрисовка. Выделен отдельно для
 * тестов; обычный цикл — editor_run(). */
void editor_frame(float dt);

/* Главный цикл редактора; возвращается по выходу (ESC без изменений,
 * «Сохранить» в окне выхода, закрытие окна). */
void editor_run(void);

/* Освобождает ресурсы редактора (тайлы, карту и инвентари объектов). */
void editor_shutdown(void);

#endif /* EDITOR_H */
